export function displayState(value: string): string {
  if (labels[value]) return labels[value]
  const [subject, action, extra] = value.split('.')
  return !extra && eventSubjects[subject] && eventActions[action]
    ? `${eventSubjects[subject]}${eventActions[action]}`
    : value
}
